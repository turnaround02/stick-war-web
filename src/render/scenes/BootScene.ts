import Phaser from 'phaser';
import type { UnitTypeId } from '../../data/units';
import { stripKey } from '../stickman/sprite';

/** The unit types that have sprite assets (all 6 trainable types). */
const SPRITE_TYPES: readonly UnitTypeId[] = [
  'miner', 'swordsman', 'archer', 'spearman', 'giant', 'mage',
];

/** Every unit walks; every combat type but the miner attacks (M15). */
const ATTACK_TYPES: readonly UnitTypeId[] = [
  'swordsman', 'archer', 'spearman', 'giant', 'mage',
];

/** Frames per strip — MUST match the pipeline's FRAMES_PER_STRIP contract. */
const STRIP_FRAMES = 6;

/**
 * Entry scene. M1 has nothing else to preload (all other art is procedural),
 * so it immediately hands off — since M7 to the LEVEL MENU rather than a
 * battle.
 *
 * M15: the pixel-art ANIMATION strips are preloaded here so BattleScene can
 * play them without a loading stall. They live in public/sprites-sheets/ and
 * are generated by `npm run sheets` (scripts/make-sheets.ts). If files are
 * absent the texture load fails silently and the type falls back to the
 * skeleton renderer — the game is never blank (M14's rule, per type).
 */
export class BootScene extends Phaser.Scene {
  constructor() {
    super({ key: 'Boot' });
  }

  preload(): void {
    for (const typeId of SPRITE_TYPES) {
      this.load.image(stripKey(typeId, 'walk'), `sprites-sheets/${typeId}-walk.png`);
    }
    for (const typeId of ATTACK_TYPES) {
      this.load.image(stripKey(typeId, 'attack'), `sprites-sheets/${typeId}-attack.png`);
    }
  }

  create(): void {
    // Frame widths differ per type (18-42px after downscale), so they cannot
    // be hardcoded at load time. The pipeline emits a uniform grid whose frame
    // width is strip.width / FRAMES, so split the loaded image into frames
    // here — texture.add is the same cut the spritesheet parser would do.
    for (const typeId of SPRITE_TYPES) {
      this.registerStrip(stripKey(typeId, 'walk'), STRIP_FRAMES);
    }
    for (const typeId of ATTACK_TYPES) {
      this.registerStrip(stripKey(typeId, 'attack'), STRIP_FRAMES);
    }
    this.scene.start('Menu');
  }

  /** Splits a loaded strip image into FRAMES uniform frames (no-op if absent). */
  private registerStrip(key: string, frames: number): void {
    if (!this.textures.exists(key)) return;
    const tex = this.textures.get(key);
    const source = tex.source[0];
    if (!source) return;
    const fw = Math.floor(source.width / frames);
    const fh = source.height;
    if (fw <= 0 || fh <= 0) return;
    for (let i = 0; i < frames; i++) {
      const name = String(i);
      if (!tex.has(name)) tex.add(name, 0, i * fw, 0, fw, fh);
    }
  }
}
