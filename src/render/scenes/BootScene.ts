import Phaser from 'phaser';
import type { UnitTypeId } from '../../data/units';
import { spriteKey } from '../stickman/sprite';

/** The unit types that have a sprite asset (all 6 trainable types). */
const SPRITE_TYPES: readonly UnitTypeId[] = [
  'miner', 'swordsman', 'archer', 'spearman', 'giant', 'mage',
];

/**
 * Entry scene. M1 has nothing to preload (all art is procedural), so it
 * immediately hands off — since M7 to the LEVEL MENU rather than a battle.
 *
 * M14: the pixel-art idle sprites are preloaded here so BattleScene can use
 * them without a loading stall. The sprites live in public/sprites/ and are
 * generated by `npm run sprites` (scripts/make-sprites.ts). If the files are
 * absent the texture load fails silently and the game falls back to the
 * skeleton renderer — the game is never blank.
 */
export class BootScene extends Phaser.Scene {
  constructor() {
    super({ key: 'Boot' });
  }

  preload(): void {
    for (const typeId of SPRITE_TYPES) {
      this.load.image(spriteKey(typeId), `sprites/${typeId}.png`);
    }
  }

  create(): void {
    this.scene.start('Menu');
  }
}
